import AppKit
import Combine
import Foundation

struct ClipboardEntry: Identifiable {
    let id = UUID()
    let capturedAt: Date
    let text: String?
    let tiffData: Data?

    var preview: String {
        if let text {
            return String(text.replacingOccurrences(of: "\n", with: " ").prefix(100))
        }
        return "Image"
    }
}

@MainActor
final class ClipboardHistoryStore: ObservableObject {
    static let shared = ClipboardHistoryStore()

    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var isRecording = false

    private var timer: Timer?
    private var lastChangeCount = -1
    private let maximumItems = 10
    private let maximumImageSize = 20_000_000

    func startRecording() {
        guard timer == nil else { return }

        lastChangeCount = NSPasteboard.general.changeCount
        isRecording = true

        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) {
            [weak self] _ in
            Task { @MainActor in
                self?.captureIfChanged()
            }
        }
    }

    func stopRecording() {
        timer?.invalidate()
        timer = nil
        isRecording = false
    }

    func clearHistory() {
        entries.removeAll()
    }

    func restoreToClipboard(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        if let text = entry.text {
            pasteboard.setString(text, forType: .string)
        } else if let data = entry.tiffData {
            pasteboard.setData(data, forType: .tiff)
        }

        lastChangeCount = pasteboard.changeCount
    }

    private func captureIfChanged() {
        let pasteboard = NSPasteboard.general

        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        let privateTypes = [
            NSPasteboard.PasteboardType(rawValue: "org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType(rawValue: "org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType(rawValue: "org.nspasteboard.AutoGeneratedType")
        ]

        // These markers are used by some apps for sensitive/temporary content.
        guard !privateTypes.contains(where: { types.contains($0) }) else {
            return
        }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(ClipboardEntry(capturedAt: Date(), text: text, tiffData: nil))
            return
        }

        if let imageData = pasteboard.data(forType: .tiff),
           imageData.count <= maximumImageSize {
            add(ClipboardEntry(capturedAt: Date(), text: nil, tiffData: imageData))
        }
    }

    private func add(_ entry: ClipboardEntry) {
        entries.insert(entry, at: 0)

        if entries.count > maximumItems {
            entries = Array(entries.prefix(maximumItems))
        }
    }
}

